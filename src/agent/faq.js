/** FAQ 检索：返回最佳匹配（无则 null） */
export function matchFaq(text) {
  const t = (text || '').toLowerCase().trim()
  if (!t) return null
  let best = null
  let bestScore = 0
  for (const f of FAQ) {
    let score = 0
    for (const p of f.patterns) {
      const pl = p.toLowerCase()
      if (t === pl) score = Math.max(score, 100)
      else if (t.includes(pl)) score = Math.max(score, 60 + pl.length * 3)
      else if (pl.includes(t) && t.length >= 2) score = Math.max(score, 45 + t.length * 3)
    }
    if (score > bestScore) { bestScore = score; best = f }
  }
  return bestScore >= 45 ? best : null
}
